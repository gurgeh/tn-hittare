"""Step 0 report: ``reports/step0_stats.md``.

    uv run python -m tnh.data.report

Reads ``corpus/games.parquet``, ``corpus/games_extra.parquet``,
``corpus/positions.parquet`` and ``corpus/parse_stats.json`` and writes the
tables the step-0 decision rests on. Everything in it is computed here except
the paragraph on the hand spot-checks, which records what was found when the
listed games were looked at (the samples are drawn with a fixed seed, so the
same games are listed on every run of the same corpus).
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import polars as pl

from tnh.data.window import in_window
from tnh.paths import CORPUS, DATA_ROOT, REPORTS

BANDS = {"1800-2500": (1800, 2500), "2100-2300": (2100, 2300)}
PLY_BUCKETS = [(30, 39), (40, 49), (50, 59), (60, 69), (70, 79)]
BOOK_COUNTS = [2, 5, 20, 100]
SEED = 20261111

SPOT_CHECK_FINDINGS = """\
What was found when the two samples below were looked at by hand (corpus
built 2026-11-11; the samples are drawn with a fixed seed, so a rebuild of
the same dumps lists the same games):

- **unknown (20 games).** None has a TimeControl tag, a clock comment or a
  tempo word in its names; they are DGT relays without clocks. Sixteen are
  from events that are classical by their nature: open tournaments
  (Cambridge, Manaus twice, Ustroń, Roquetas, Rio Grande IRT, Gujarat,
  Warakomska Memorial, Pfälzischer Kongress, Ljubljana, Figueira da Foz),
  Sharjah Masters, the Malopolska and Portuguese youth championships, and
  the Swiss and Slovak team leagues. Four are uncertain and may well be
  rapid: the Polish U6/U7 championship, the Norwegian "Mikroputt" class,
  Turkish U8 girls, and the Polish junior team league. So `unknown` is
  mostly lost classical games, not a bin of doubtful ones. The table above
  shows how many unknown games share a broadcast round with games of a
  known tempo: giving such a game its round's tempo would recover most of
  them, but needs a fifth `tempo_source` value, a change to DESIGN.md that
  is not made here.
- **classical (20 games).** All twenty are classical events. Nineteen
  have a 90-minute base: 90+30 in seventeen (one of them the Olympiad's
  40/90+30), 90+60 estimated for the Greek team championship, 90+20
  estimated for Flemish seniors (most likely 90+30 with the increment
  underestimated; the tempo is the same). The twentieth is the Varsity
  Match, 110+5. Nine were decided by the tag with the clocks agreeing,
  eleven by the clocks alone. The first clock readings fit the control in
  every game (5 007-5 458 s for 90 minutes; the low ones are a player who
  arrived late or thought long over move 1).
"""


def band_expr(white: str, black: str, lo: int, hi: int) -> pl.Expr:
    return pl.col(white).is_between(lo, hi) & pl.col(black).is_between(lo, hi)


def md_table(df: pl.DataFrame, floatfmt: str = "{:.1%}") -> str:
    cols = df.columns
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---:" if df[c].dtype.is_numeric() else "---" for c in cols) + "|"]
    for row in df.iter_rows():
        cells = []
        for v in row:
            if isinstance(v, float):
                cells.append(floatfmt.format(v))
            elif isinstance(v, int):
                cells.append(f"{v:,}".replace(",", " "))
            else:
                cells.append("" if v is None else str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def du(path: Path) -> str:
    out = subprocess.run(["du", "-sh", str(path)], capture_output=True, text=True, check=True).stdout
    return out.split()[0]


def main() -> None:
    games = pl.read_parquet(CORPUS / "games.parquet")
    extra = pl.read_parquet(CORPUS / "games_extra.parquet")
    stats = json.loads((CORPUS / "parse_stats.json").read_text())
    g = games.join(extra, on="game_id")
    both = pl.col("white_elo").is_not_null() & pl.col("black_elo").is_not_null()
    g = g.with_columns(
        band=pl.when(~both).then(pl.lit("rating missing"))
        .when(band_expr("white_elo", "black_elo", 2100, 2300)).then(pl.lit("2100-2300"))
        .when(band_expr("white_elo", "black_elo", 1800, 2500)).then(pl.lit("1800-2500, not 2100-2300"))
        .otherwise(pl.lit("other ratings")),
        in_1800_2500=both & band_expr("white_elo", "black_elo", 1800, 2500),
    )
    out: list[str] = []
    w = out.append
    w("# Step 0: the corpus of OTB games from Lichess broadcasts\n")
    w("Generated by `uv run python -m tnh.data.report` from `corpus/` under "
      f"`{DATA_ROOT}`. Source: the 81 monthly Lichess broadcast dumps 2020-01 to 2026-09.\n")

    # --- headline
    cl = g.filter(pl.col("tempo") == "classical")
    n_cl_1825 = cl.filter(pl.col("in_1800_2500")).height
    n_cl_2123 = cl.filter(pl.col("band") == "2100-2300").height
    w("## Headline\n")
    w(f"- Games read: {stats['games_read']:,}; kept: {stats['games_kept']:,} in {stats['tournaments']:,} tournaments.")
    w(f"- Classical games: {cl.height:,}. Both players 1800-2500: **{n_cl_1825:,}** "
      f"({cl.filter(pl.col('in_1800_2500') & pl.col('has_clock')).height:,} with clocks). "
      f"Both 2100-2300: **{n_cl_2123:,}** ({cl.filter((pl.col('band') == '2100-2300') & pl.col('has_clock')).height:,} with clocks).")
    w("")

    # --- by tempo, year, band
    w("## Games by tempo, year and rating band\n")
    t = g.group_by("year", "tempo").len().pivot(on="tempo", index="year", values="len").sort("year", nulls_last=True)
    t = t.with_columns(pl.exclude("year").fill_null(0))
    t = t.select("year", *[c for c in ["classical", "rapid", "blitz", "unknown"] if c in t.columns])
    w(md_table(t.with_columns(pl.col("year").cast(pl.String).fill_null("no date"))) + "\n")
    t = g.group_by("band", "tempo").len().pivot(on="tempo", index="band", values="len").fill_null(0).sort("band")
    t = t.select("band", *[c for c in ["classical", "rapid", "blitz", "unknown"] if c in t.columns])
    w("Rating bands are exclusive rows here; \"1800-2500\" in the rest of the report includes 2100-2300. "
      "Ratings are the PGN `WhiteElo`/`BlackElo` as given; for rapid and blitz events they may be rapid or blitz ratings.\n")
    w(md_table(t) + "\n")

    # --- clocks
    w("## Clocks\n")
    w("`has_clock`: at least 80 % of the moves carry `%clk`.\n")
    t = g.group_by("band", "tempo").agg(games=pl.len(), with_clock=pl.col("has_clock").sum(), share=pl.col("has_clock").mean()).sort("band", "tempo")
    w(md_table(t) + "\n")
    t = g.group_by("year").agg(games=pl.len(), share_with_clock=pl.col("has_clock").mean()).sort("year", nulls_last=True)
    w(md_table(t.with_columns(pl.col("year").cast(pl.String).fill_null("no date"))) + "\n")

    # --- tempo source
    w("## How tempo was decided\n")
    w("Order: a readable TimeControl tag, unless the first clock readings clearly contradict it; "
      "else the clocks (base from the first readings, increment from the gains between a player's clocks); "
      "else tempo words in the broadcast or event name; else `unknown`. "
      "Without clocks, a classical tag in an event whose name says rapid, blitz or tiebreak gives `unknown`.\n")
    t = g.group_by("tempo_source", "tempo").len().sort("tempo_source", "tempo")
    w(md_table(t) + "\n")
    t = g.group_by("tempo_note").len().sort("len", descending=True).rename({"tempo_note": "detail", "len": "games"})
    w("In detail (`tag_<how the tag was read>_<what happened>`):\n")
    w(md_table(t) + "\n")
    w(f"**Unknown: {g.filter(pl.col('tempo') == 'unknown').height:,} games**, "
      f"{g.filter((pl.col('tempo') == 'unknown') & pl.col('in_1800_2500')).height:,} of them with both players 1800-2500.\n")
    gr = g.with_columns(rid=pl.col("game_url").str.extract(r"/broadcast/[^/]+/[^/]+/([^/]+)/"))
    r = gr.group_by("rid").agg(
        known=pl.col("tempo").filter(pl.col("tempo") != "unknown").unique(),
        unknown=(pl.col("tempo") == "unknown").sum(),
    ).filter(pl.col("unknown") > 0)
    r = r.with_columns(
        round_tempo=pl.when(pl.col("known").list.len() == 0).then(pl.lit("(all games in the round unknown)"))
        .when(pl.col("known").list.len() == 1).then(pl.col("known").list.first())
        .otherwise(pl.lit("(mixed)"))
    )
    t = r.group_by("round_tempo").agg(unknown_games=pl.col("unknown").sum()).sort("unknown_games", descending=True)
    w("Unknown games by the tempo of the other games in the same broadcast round:\n")
    w(md_table(t) + "\n")

    w("### Spot checks\n")
    w(SPOT_CHECK_FINDINGS)
    for tempo in ("unknown", "classical"):
        s = g.filter(pl.col("tempo") == tempo).sample(20, seed=SEED if tempo == "unknown" else SEED + 1)
        s = s.select(
            pl.col("broadcast_name").str.slice(0, 60),
            pl.col("time_control_raw").str.slice(0, 40).alias("TimeControl"),
            "tempo_source",
            "base_s",
            "inc_s",
            pl.col("clocks_s").list.head(2).cast(pl.List(pl.String)).list.join(", ").alias("first clocks"),
            "white_elo",
            pl.col("game_url"),
        )
        w(f"\n{tempo}, 20 games (seed {SEED if tempo == 'unknown' else SEED + 1}):\n")
        w(md_table(s) + "\n")

    # --- window
    pos_path = CORPUS / "positions.parquet"
    pos = pl.scan_parquet(pos_path).select("game_id", "ply", "pos_count", "clock_mover_s", "mover_elo", "opp_elo", "split")
    w("## Rows in the window\n")
    w(f"`positions.parquet`: {pl.scan_parquet(pos_path).select(pl.len()).collect().item():,} rows "
      "(classical games with both ratings, plies below 80). A row is in a band when both the mover and the opponent are.\n")
    rows = []
    for bname, (lo, hi) in BANDS.items():
        for bc in BOOK_COUNTS:
            q = pos.filter(in_window(pos, book_count=bc)).filter(band_expr("mover_elo", "opp_elo", lo, hi))
            t = q.group_by("split").agg(rows=pl.len(), games=pl.col("game_id").n_unique()).collect()
            d = {r["split"]: (r["rows"], r["games"]) for r in t.iter_rows(named=True)}
            rows.append({"band": bname, "book_count": bc, **{f"{s} rows": d.get(s, (0, 0))[0] for s in ("train", "val", "test")},
                         "test games": d.get("test", (0, 0))[1], "all rows": sum(v[0] for v in d.values())})
    win = pl.DataFrame(rows)
    w("Defaults: `book_count=5, max_ply=60, min_clock_s=600`.\n")
    w(md_table(win.filter(pl.col("book_count") == 5)) + "\n")
    w("### Sensitivity to book_count\n")
    w("Same, with `book_count` 2, 5, 20, 100 (`max_ply` and `min_clock_s` at their defaults):\n")
    w(md_table(win) + "\n")
    oob = (
        pos.filter(band_expr("mover_elo", "opp_elo", 1800, 2500))
        .group_by("game_id")
        .agg(*[pl.col("ply").filter(pl.col("pos_count") < bc).min().alias(f"bc{bc}") for bc in BOOK_COUNTS])
        .collect()
    )
    t = pl.DataFrame({
        "book_count": BOOK_COUNTS,
        "median ply out of book": [oob[f"bc{bc}"].median() for bc in BOOK_COUNTS],
        "games never out of book before ply 80": [oob[f"bc{bc}"].null_count() for bc in BOOK_COUNTS],
    })
    w("Where games (1800-2500) leave book:\n")
    w(md_table(t, "{:.0f}") + "\n")

    # --- time trouble
    w("## Time trouble by ply (the decision for this step)\n")
    w("Classical games with clocks (`has_clock`), both players 1800-2500. The clock is the mover's, before the move. "
      "Ply 50-59 is moves 26-30. Controls are `base_s+inc_s` of the first period (from the tag, or estimated from the clocks).\n")
    gc = games.filter((pl.col("tempo") == "classical") & pl.col("has_clock")).select(
        "game_id", "base_s", "inc_s", "time_control_raw", "tempo_source"
    )
    gc = gc.with_columns(
        control=(pl.col("base_s") // 60).cast(pl.String) + "+" + pl.col("inc_s").cast(pl.String),
    )
    top = gc.group_by("control").len().sort("len", descending=True).head(6)["control"].to_list()
    gc = gc.with_columns(control=pl.when(pl.col("control").is_in(top)).then(pl.col("control")).otherwise(pl.lit("other")))
    pt = (
        pos.filter(band_expr("mover_elo", "opp_elo", 1800, 2500) & pl.col("clock_mover_s").is_not_null() & (pl.col("ply") >= 30))
        .join(gc.lazy(), on="game_id", how="inner")
        .with_columns(bucket=(pl.col("ply") // 10 * 10))
    )
    t = (
        pt.group_by("control", "bucket")
        .agg(moves=pl.len(), lt10=(pl.col("clock_mover_s") < 600).mean(), lt5=(pl.col("clock_mover_s") < 300).mean())
        .collect()
    )
    for label, col in (("< 10 minutes", "lt10"), ("< 5 minutes", "lt5")):
        p = t.with_columns(bucket=pl.format("ply {}-{}", pl.col("bucket"), pl.col("bucket") + 9)).pivot(on="bucket", index="control", values=col)
        allc = pt.group_by("bucket").agg(v=(pl.col("clock_mover_s") < (600 if col == "lt10" else 300)).mean()).collect()
        allrow = {"control": "all"} | {f"ply {b}-{b + 9}": v for b, v in allc.iter_rows()}
        p = pl.concat([p, pl.DataFrame([allrow])], how="diagonal")
        order = ["control"] + [f"ply {a}-{b}" for a, b in PLY_BUCKETS]
        counts = t.group_by("control").agg(moves=pl.col("moves").sum())
        p = p.join(counts, on="control", how="left").select(*order, "moves")
        w(f"Share of moves made with **{label}** on the mover's clock:\n")
        w(md_table(p.sort("moves", descending=True, nulls_last=True)) + "\n")
    gp = (
        pt.group_by("game_id", (pl.col("ply") % 2).alias("side"))
        .agg(first_lt10=pl.col("ply").filter(pl.col("clock_mover_s") < 600).min(),
             first_lt5=pl.col("ply").filter(pl.col("clock_mover_s") < 300).min())
        .collect()
    )
    n_sides = gp.height
    t = pl.DataFrame({
        "before ply": [40, 50, 60, 70, 80],
        "player-games below 10 min": [gp.filter(pl.col("first_lt10") < c).height / n_sides for c in (40, 50, 60, 70, 80)],
        "player-games below 5 min": [gp.filter(pl.col("first_lt5") < c).height / n_sides for c in (40, 50, 60, 70, 80)],
    })
    w(f"Share of player-games ({n_sides:,}, both sides of each game, all controls) where the mover's clock "
      "went below the limit at some ply from 30 up to the given ply:\n")
    w(md_table(t) + "\n")

    # --- drops
    w("## What was dropped, and why\n")
    w(f"Read {stats['games_read']:,} games, kept {stats['games_kept']:,}.\n")
    expl = {
        "result_not_final": "Result `*`: unfinished when the dump was taken, or never updated",
        "online": "Online events relayed as broadcasts (names with \"Online\", Chess.com events, corporate leagues); see `sources.ONLINE_RE`",
        "no_moves": "No moves: forfeits, byes, pairings without a game",
        "duplicate": "The same game (white surname, black surname, year, moves) in more than one broadcast; the copy with clocks kept",
        "engine": "Engine games: TCEC, CCC and other engine events, or a BOT title",
        "variant": "Variant tag not Standard (Chess960, Fischerandom, Crazyhouse, King of the Hill, Antichess)",
        "non_standard_start": "FEN tag with a non-standard start (Chess960 tagged as Standard, From Position)",
        "illegal_move": "An illegal move in the move text (relay errors); the whole game is dropped",
        "result_contradicts_final_position": "The final position is mate or stalemate and the result says otherwise",
        "simul": "Simultaneous exhibitions",
        "result_other": "Result neither `1-0`, `0-1`, `1/2-1/2` nor `*` (`1:0`, `½-½`, `+/-`, ...)",
        "ambiguous_move": "An ambiguous SAN move",
        "invalid_san": "Unreadable SAN",
        "result_token_mismatch": "The result at the end of the move text differs from the Result tag",
        "malformed_movetext": "Unbalanced variation brackets",
        "null_move": "A null move (`--`)",
    }
    t = pl.DataFrame({"reason": list(stats["dropped"]), "games": list(stats["dropped"].values())}).with_columns(
        meaning=pl.col("reason").replace_strict(expl, default="")
    )
    w(md_table(t) + "\n")
    w("Kept, not dropped: team events (Bundesliga, 4NCL, Olympiads), whose tournament id is the competition, "
      "so the split keeps a whole season or Olympiad together; tiebreak and armageddon games inside classical "
      "events, which are rapid or blitz by their tag or clocks; and games without ratings, which stay in "
      "`games.parquet` but give no positions.\n")
    tour = games.group_by("tournament_id").len().sort("len", descending=True)
    w(f"Tournaments: {tour.height:,}. The largest has {tour['len'][0]:,} games "
      f"({tour['len'][0] / games.height:.2%} of the corpus): `{tour['tournament_id'][0]}`. "
      f"Split of all games: " + ", ".join(f"{s} {n:,}" for s, n in games.group_by("split").len().sort("split").iter_rows()) + ".\n")

    # --- disk
    w("## Disk\n")
    for sub in ("raw/lichess_broadcast", "corpus"):
        p = DATA_ROOT / sub
        if p.exists():
            w(f"- `{sub}/`: {du(p)}")
    w(f"- all of `{DATA_ROOT}` (other modules' data included): {du(DATA_ROOT)}")
    for f in ("games.parquet", "positions.parquet"):
        p = CORPUS / f
        w(f"- `corpus/{f}`: {p.stat().st_size / 1e9:.2f} GB")
    w(f"- free on the volume: {shutil.disk_usage(DATA_ROOT).free / 1e9:.0f} GB")

    REPORTS.mkdir(parents=True, exist_ok=True)
    path = REPORTS / "step0_stats.md"
    path.write_text("\n".join(out) + "\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
